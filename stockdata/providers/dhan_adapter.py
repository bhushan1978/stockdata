"""Dhan adapter: a thin wrapper around the existing, unchanged :class:`stockdata.dhan.DhanClient`.

Nothing about how Dhan is requested, retried, rate-limited or validated differs from before; this class only presents it
through the common interface. Facts marked ``probe_verified`` were established with the project's own live ``verify-api``
runs on 2026-10-10 (see docs/RUNBOOK.md); the rest are the provider's published numbers.

Dhan's historical-data endpoints need the paid Data API plan. That is why routine updates can be pointed at another
authorised provider (Providers screen) while Dhan stays available for backfill and verification.
"""
from __future__ import annotations

from datetime import date
from typing import Mapping

from stockdata import config
from stockdata.dhan import DhanAuthError, DhanClient, RateLimiter
from stockdata.instruments import Instrument
from stockdata.providers import base
from stockdata.providers.base import (AuthRequirement, Capabilities, ConnectionResult, CredentialField, DOCUMENTED, PROBE_VERIFIED,
                                      RateLimit, RawResponse, TimeframeSupport, UNKNOWN)
from stockdata.providers.errors import AuthError, PermanentError, ProviderSetupError
from stockdata.validation import Validated, validate_response

TOKEN_KEY, CLIENT_KEY = "DHAN_ACCESS_TOKEN", "DHAN_CLIENT_ID"


class DhanAdapter(base.ProviderAdapter):
    name = "dhan"
    label = "Dhan (DhanHQ v2)"

    def capabilities(self) -> Capabilities:
        return Capabilities(
            provider=self.name, label=self.label,
            timeframes={
                "daily": TimeframeSupport(True, "daily", None, config.DAILY_HISTORY_START, PROBE_VERIFIED,
                                          "one request covered 1990 to today for a large cap (6,159 candles) in the project's "
                                          "live verification; an empty range answers HTTP 400 DH-907 (ambiguous, never read as 'no data')"),
                "15min": TimeframeSupport(True, "15-minute", config.MAX_INTRADAY_WINDOW_DAYS, None, PROBE_VERIFIED,
                                          f"windows of {config.DEFAULT_INTRADAY_WINDOW_DAYS} days work; about "
                                          f"{config.INTRADAY_HISTORY_YEARS} years of history (earliest date set at the first run)"),
            },
            rate_limit=RateLimit(per_second=5, per_day=100_000, operating_day_cap=80_000, status=DOCUMENTED,
                                 note="Dhan documents 5 requests/second and 100,000 requests/day, account-wide: other programs "
                                      "using the same account are not counted by this application's ledger"),
            auth=AuthRequirement(
                fields=(CredentialField(TOKEN_KEY, "Access token", secret=True),
                        CredentialField(CLIENT_KEY, "Client ID", secret=False)),
                token_kind="DhanHQ access token (JWT) and client id",
                lifetime="set when the token is generated in the Dhan web console; the expiry is read from the token",
                interactive_login=True,
                unattended_note=("Works unattended while the token is valid. A new token must be generated by a person in the Dhan "
                                 "console; the application warns before expiry and shows ACTION REQUIRED after it. The historical "
                                 "data endpoints require Dhan's paid Data API plan."),
                warn_before_seconds=2 * 86400,
                how_to_obtain="Generate an access token in the Dhan web console (DhanHQ APIs) and paste it with your client id."),
            adjustment_basis="adjusted", adjustment_status=DOCUMENTED,
            intraday_polling=True,
            instrument_mapping="the Dhan security id and exchange segment from the instrument master (exact, no guessing)",
            sources=("project live verification 2026-10-10 (docs/RUNBOOK.md, docs/CORPORATE_ACTIONS.md)",
                     "Dhan's published limits"),
            extra={"adjustment_note": "history appears already split/bonus adjusted (docs/CORPORATE_ACTIONS.md); not verified "
                                      "against NSE, so treated as 'adjusted, unverified'"})

    def token_env_key(self) -> str:
        return TOKEN_KEY

    def map_instrument(self, inst: Instrument) -> str | None:
        return str(inst.security_id)

    def window_days(self, tf) -> int:
        return tf.default_window_days

    def earliest(self, tf) -> date | None:
        return config.DAILY_HISTORY_START if not tf.is_intraday else None      # intraday: pinned at the first run

    # ---------------------------------------------------------------------------------------- client
    def make_client(self, env: Mapping[str, str], *, settings, label: str, budget=None, session=None,
                    max_attempts: int = 5, limiter=None) -> DhanClient:
        token = settings.require_token()
        return DhanClient(token, settings.base_url, client_id=settings.client_id, limiter=limiter or RateLimiter(settings.rps),
                          max_attempts=max_attempts, budget=budget, session=session)

    def fetch(self, client: DhanClient, inst: Instrument, tf, window, opts) -> RawResponse:
        payload = tf.payload(inst, window.start, window.end, intraday_date_format=opts.intraday_date_format, client_id=opts.client_id)
        resp = client.post(tf.endpoint, payload)
        return RawResponse(resp.data, resp.http_status, resp.attempts)

    def to_canonical(self, tf, raw: RawResponse, window) -> Validated:
        return validate_response(tf, raw.body, window)

    def test_connection(self, client: DhanClient) -> ConnectionResult:
        try:
            body = client.get_json("/profile")
        except DhanAuthError as exc:
            return ConnectionResult(False, "auth_failed", f"Dhan rejected the token ({exc.message}); generate a new one",
                                    requests_used=client.requests_sent)
        except PermanentError as exc:
            return ConnectionResult(False, "rejected", f"Dhan refused the profile request: {exc.message}", requests_used=client.requests_sent)
        except Exception as exc:                      # noqa: BLE001
            return ConnectionResult(False, "network", f"could not complete the test: {type(exc).__name__}: {exc}", requests_used=client.requests_sent)
        details = {}
        if isinstance(body, dict):                    # plan information only; nothing that identifies the person
            for src, dst in (("dataPlan", "data_plan"), ("dataValidity", "data_validity"), ("tokenValidity", "token_validity")):
                if body.get(src) not in (None, ""):
                    details[dst] = str(body[src])[:40]
        return ConnectionResult(True, "ok", "Dhan accepted the token" + ("" if details else " (the answer carried no plan details)"),
                                requests_used=client.requests_sent, details=details)
